#!/usr/bin/env python3
"""Generate gui/ThemeTokens.inc from base hue, accent hue, and contrast targets using OKLCH."""

import math
import sys

def oklch_to_srgb(L: float, C: float, h_deg: float) -> str:
    h = math.radians(h_deg)
    a = C * math.cos(h)
    b = C * math.sin(h)

    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b

    l = l_ ** 3
    m = m_ ** 3
    s = s_ ** 3

    r = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s

    def encode(v: float) -> int:
        v = max(0.0, min(1.0, v))
        v = 12.92 * v if v <= 0.0031308 else 1.055 * (v ** (1.0 / 2.4)) - 0.055
        return max(0, min(255, round(v * 255)))

    return f"#{encode(r):02x}{encode(g):02x}{encode(bl):02x}"


LIGHT_L = [0.992, 0.968, 0.948, 0.922, 0.898, 0.865, 0.640, 0.560, 0.505, 0.450, 0.440, 0.235]
DARK_L  = [0.165, 0.195, 0.230, 0.260, 0.290, 0.330, 0.525, 0.525, 0.545, 0.515, 0.790, 0.955]

LIGHT_HC_L = [1.000, 0.972, 0.945, 0.915, 0.885, 0.640, 0.560, 0.480, 0.490, 0.425, 0.350, 0.145]
DARK_HC_L  = [0.120, 0.160, 0.205, 0.245, 0.285, 0.505, 0.545, 0.530, 0.535, 0.495, 0.845, 0.985]


def generate_scale(hue: float, chroma: float, targets: list[float]) -> list[str]:
    return [oklch_to_srgb(L, chroma if i >= 2 else chroma * 0.4, hue) for i, L in enumerate(targets)]


def main() -> int:
    base_hue = float(sys.argv[1]) if len(sys.argv) > 1 else 250.0
    accent_hue = float(sys.argv[2]) if len(sys.argv) > 2 else 262.0

    scales = {
        "kLightNeutral":   generate_scale(base_hue, 0.006, LIGHT_L),
        "kLightAccent":    generate_scale(accent_hue, 0.145, LIGHT_L),
        "kLightSuccess":   generate_scale(152.0, 0.130, LIGHT_L),
        "kLightWarning":   generate_scale(72.0, 0.135, LIGHT_L),
        "kLightDanger":    generate_scale(25.0, 0.155, LIGHT_L),
        "kDarkNeutral":    generate_scale(base_hue, 0.006, DARK_L),
        "kDarkAccent":     generate_scale(accent_hue, 0.145, DARK_L),
        "kDarkSuccess":    generate_scale(152.0, 0.130, DARK_L),
        "kDarkWarning":    generate_scale(72.0, 0.135, DARK_L),
        "kDarkDanger":     generate_scale(25.0, 0.155, DARK_L),
        "kLightHcNeutral": generate_scale(base_hue, 0.004, LIGHT_HC_L),
        "kLightHcAccent":  generate_scale(accent_hue, 0.155, LIGHT_HC_L),
        "kLightHcSuccess": generate_scale(152.0, 0.135, LIGHT_HC_L),
        "kLightHcWarning": generate_scale(72.0, 0.140, LIGHT_HC_L),
        "kLightHcDanger":  generate_scale(25.0, 0.165, LIGHT_HC_L),
        "kDarkHcNeutral":  generate_scale(base_hue, 0.004, DARK_HC_L),
        "kDarkHcAccent":   generate_scale(accent_hue, 0.155, DARK_HC_L),
        "kDarkHcSuccess":  generate_scale(152.0, 0.135, DARK_HC_L),
        "kDarkHcWarning":  generate_scale(72.0, 0.140, DARK_HC_L),
        "kDarkHcDanger":   generate_scale(25.0, 0.165, DARK_HC_L),
    }

    print("// Generated by scripts/generate_tokens.py from OKLCH step targets.")
    for name, values in scales.items():
        items = ", ".join(f'"{v}"' for v in values)
        print(f"const char* const {name}[12] = {{{items}}};")
    print(f'const char* const kLightControl = "{oklch_to_srgb(0.640, 0.006, base_hue)}";')
    print(f'const char* const kDarkControl = "{oklch_to_srgb(0.515, 0.006, base_hue)}";')
    print(f'const char* const kLightHcControl = "{oklch_to_srgb(0.480, 0.004, base_hue)}";')
    print(f'const char* const kDarkHcControl = "{oklch_to_srgb(0.600, 0.004, base_hue)}";')
    print(f'const char* const kLightTextOff = "{oklch_to_srgb(0.655, 0.006, base_hue)}";')
    print(f'const char* const kDarkTextOff = "{oklch_to_srgb(0.475, 0.006, base_hue)}";')
    print(f'const char* const kLightHcTextOff = "{oklch_to_srgb(0.620, 0.004, base_hue)}";')
    print(f'const char* const kDarkHcTextOff = "{oklch_to_srgb(0.510, 0.004, base_hue)}";')
    print(f'const char* const kOnSolid = "{oklch_to_srgb(1.000, 0.000, base_hue)}";')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
